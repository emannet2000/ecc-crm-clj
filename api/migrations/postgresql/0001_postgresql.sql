 INSERT INTO finance_audit(kind,record_id,action,details,actor_id,actor_name) VALUES ('payment',NEW.id,CASE WHEN NEW.reverses_id IS NULL THEN 'receipt' ELSE 'reversal' END,jsonb_build_object('invoiceId',NEW.invoice_id,'amountMinor',NEW.amount_minor,'paidOn',NEW.paid_on,'method',NEW.method,'reference',NEW.reference,'reason',NEW.reason,'reversesId',NEW.reverses_id),NEW.actor_id,NEW.actor_name);
