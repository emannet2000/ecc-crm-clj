CREATE FUNCTION ecc_trigger_bank_match_validate() RETURNS trigger LANGUAGE plpgsql AS $trigger$
BEGIN
 IF NEW.payment_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM bank_lines b JOIN invoice_payments p ON p.id=NEW.payment_id JOIN invoices i ON i.id=p.invoice_id WHERE b.id=NEW.bank_line_id AND b.currency=i.currency AND b.amount_minor=p.amount_minor AND NOT EXISTS(SELECT 1 FROM invoice_payments r WHERE r.reverses_id=p.id)) THEN RAISE EXCEPTION 'Bank payment amount or currency mismatch' USING ERRCODE='23514'; END IF;
 IF NEW.expense_entry_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM bank_lines b JOIN expense_entries p ON p.id=NEW.expense_entry_id JOIN expenses e ON e.id=p.expense_id WHERE b.id=NEW.bank_line_id AND b.currency=e.currency AND b.amount_minor=-p.amount_minor AND NOT EXISTS(SELECT 1 FROM expense_entries r WHERE r.reverses_id=p.id)) THEN RAISE EXCEPTION 'Bank expense amount or currency mismatch' USING ERRCODE='23514'; END IF;
 RETURN NEW;
