CREATE FUNCTION ecc_trigger_expense_entry_validate() RETURNS trigger LANGUAGE plpgsql AS $trigger$
BEGIN
 IF NEW.posted_on>ecc_date('now',business_offset()) THEN RAISE EXCEPTION 'Future expense payment' USING ERRCODE='23514'; END IF;
 IF NEW.reverses_id IS NULL AND NOT EXISTS(SELECT 1 FROM expenses WHERE id=NEW.expense_id AND status='Approved' AND amount_minor=NEW.amount_minor) THEN RAISE EXCEPTION 'Approve the expense before recording payment' USING ERRCODE='23514'; END IF;
 IF NEW.reverses_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM expense_entries p JOIN expenses e ON e.id=p.expense_id WHERE p.id=NEW.reverses_id AND p.expense_id=NEW.expense_id AND p.reverses_id IS NULL AND NEW.amount_minor=-p.amount_minor AND NEW.posted_on>=p.posted_on AND e.status='Paid' AND length(trim(NEW.reason))>0) THEN RAISE EXCEPTION 'Invalid expense reversal' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $trigger$;
