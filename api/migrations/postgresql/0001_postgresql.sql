 INSERT INTO finance_audit(kind,record_id,action,details,actor_id,actor_name) VALUES ('expense',NEW.expense_id,CASE WHEN NEW.reverses_id IS NULL THEN 'payment' ELSE 'reversal' END,jsonb_build_object('entryId',NEW.id,'amountMinor',NEW.amount_minor,'postedOn',NEW.posted_on,'method',NEW.method,'reference',NEW.reference,'reason',NEW.reason,'reversesId',NEW.reverses_id),NEW.actor_id,NEW.actor_name);
