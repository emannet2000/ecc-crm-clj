CREATE FUNCTION ecc_trigger_payment_validate() RETURNS trigger LANGUAGE plpgsql AS $trigger$
BEGIN
 IF NEW.legacy<>0 OR NEW.paid_on IS NULL OR NEW.paid_on>ecc_date('now',business_offset()) THEN RAISE EXCEPTION 'Invalid payment date' USING ERRCODE='23514'; END IF;
 IF NOT EXISTS(SELECT 1 FROM invoices WHERE id=NEW.invoice_id AND status IN ('Issued','Paid')) THEN RAISE EXCEPTION 'Issue the invoice first' USING ERRCODE='23514'; END IF;
 IF NEW.reverses_id IS NULL AND NEW.amount_minor<0 THEN RAISE EXCEPTION 'Negative payments require a reversal' USING ERRCODE='23514'; END IF;
 IF NEW.reverses_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM invoice_payments p WHERE p.id=NEW.reverses_id AND p.invoice_id=NEW.invoice_id AND p.reverses_id IS NULL AND NEW.amount_minor=-p.amount_minor AND (p.paid_on IS NULL OR NEW.paid_on>=p.paid_on) AND length(trim(NEW.reason))>0) THEN RAISE EXCEPTION 'Invalid payment reversal' USING ERRCODE='23514'; END IF;
 IF (SELECT paid_minor+NEW.amount_minor FROM invoice_balances WHERE id=NEW.invoice_id) NOT BETWEEN 0 AND (SELECT amount_minor FROM invoices WHERE id=NEW.invoice_id) THEN RAISE EXCEPTION 'Payment exceeds the invoice balance' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $trigger$;
CREATE TRIGGER payment_validate BEFORE INSERT ON invoice_payments FOR EACH ROW EXECUTE FUNCTION ecc_trigger_payment_validate();

