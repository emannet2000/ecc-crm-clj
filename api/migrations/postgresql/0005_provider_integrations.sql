CREATE TABLE integration_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provider TEXT NOT NULL CHECK(provider IN ('zoom','google','stripe','docusign')),
 record_kind TEXT NOT NULL CHECK(record_kind IN ('appointment','invoice','contract')),
 record_id BIGINT NOT NULL,
 source_revision BIGINT NOT NULL,
 client_id BIGINT NOT NULL REFERENCES clients(id),
 case_id BIGINT REFERENCES cases(id),
 actor_id BIGINT REFERENCES users(id),
 status TEXT NOT NULL DEFAULT 'Queued' CHECK(status IN ('Queued','Running','Succeeded','Failed','Review')),
 attempts BIGINT NOT NULL DEFAULT 0,
 lease_token TEXT,
 lease_until TEXT,
 next_attempt_at TEXT,
 error_code TEXT,
 created_at TEXT NOT NULL DEFAULT(ecc_datetime('now')),
 updated_at TEXT NOT NULL DEFAULT(ecc_datetime('now')),
 UNIQUE(provider,record_kind,record_id,source_revision)
);
CREATE INDEX integration_jobs_pending ON integration_jobs(status,next_attempt_at,id);
CREATE TABLE integration_links (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL UNIQUE REFERENCES integration_jobs(id),
 provider TEXT NOT NULL,
 record_kind TEXT NOT NULL,
 record_id BIGINT NOT NULL,
 client_id BIGINT NOT NULL REFERENCES clients(id),
 case_id BIGINT REFERENCES cases(id),
 remote_id TEXT NOT NULL,
 url TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL,
 source_revision BIGINT NOT NULL,
 amount_minor BIGINT,
 currency TEXT,
 payment_id BIGINT REFERENCES invoice_payments(id),
 signed_document_id BIGINT REFERENCES documents(id),
 remote_etag TEXT,
 checked_at TEXT,
 created_at TEXT NOT NULL DEFAULT(ecc_datetime('now')),
 UNIQUE(provider,remote_id)
);
CREATE INDEX integration_links_record ON integration_links(provider,record_kind,record_id,id);
CREATE TABLE integration_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 link_id BIGINT NOT NULL REFERENCES integration_links(id),
 event_key TEXT NOT NULL UNIQUE,
 status TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT(ecc_datetime('now'))
);
CREATE FUNCTION integration_event_immutable_fn() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Integration events are immutable'; END $$;
CREATE TRIGGER integration_event_immutable BEFORE UPDATE OR DELETE ON integration_events FOR EACH ROW EXECUTE FUNCTION integration_event_immutable_fn();
CREATE TRIGGER ecc_lock BEFORE INSERT OR UPDATE OR DELETE ON integration_jobs FOR EACH STATEMENT EXECUTE FUNCTION ecc_write_lock();
CREATE TRIGGER ecc_lock BEFORE INSERT OR UPDATE OR DELETE ON integration_links FOR EACH STATEMENT EXECUTE FUNCTION ecc_write_lock();
CREATE TRIGGER ecc_lock BEFORE INSERT OR UPDATE OR DELETE ON integration_events FOR EACH STATEMENT EXECUTE FUNCTION ecc_write_lock();

