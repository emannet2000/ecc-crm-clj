#!/usr/bin/env python3
"""Generate the initial PostgreSQL baseline from the final legacy schema.

Run only while developing the baseline. Once released, add numbered PostgreSQL
migrations instead of editing the baseline. No customer database is opened.
"""
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[1]


def expression(sql):
    names = {'datetime': 'ecc_datetime', 'date': 'ecc_date', 'strftime': 'ecc_strftime',
             'printf': 'ecc_printf', 'json_object': 'jsonb_build_object',
             'json_group_object': 'jsonb_object_agg', 'json_each': 'ecc_json_each',
             'json_extract': 'ecc_json_extract', 'json': 'ecc_json',
             'json_valid': 'ecc_json_valid', 'json_type': 'jsonb_typeof'}
    # Work only outside SQL literals/comments.
    parts = re.split(r"('(?:''|[^'])*')", sql)
    for i in range(0, len(parts), 2):
        parts[i] = re.sub(r'\b(' + '|'.join(names) + r')\s*\(',
                          lambda m: names[m[1]] + '(', parts[i], flags=re.I)
        parts[i] = re.sub(r'\bIS NOT\s+(?!NULL\b|DISTINCT\b)', 'IS DISTINCT FROM ', parts[i], flags=re.I)
    return ''.join(parts)


def trigger(sql):
    match = re.fullmatch(r'CREATE TRIGGER (\w+) (BEFORE|AFTER) (.*?) ON (\w+)(.*?) BEGIN\s*(.*)\s*END', sql, re.S)
    if not match:
        raise ValueError('Unrecognized legacy trigger: ' + sql)
    name, timing, event, table, condition, body = match.groups()
    if name == 'document_request_version':
        timing, body = 'BEFORE', 'NEW.revision := OLD.revision+1;'
    if name == 'scan_content_changed':
        timing = 'BEFORE'
        body = "NEW.scan_status:='Pending'; NEW.scan_attempts:=0; NEW.scan_lease:=NULL; NEW.scan_until:=NULL; NEW.scan_detail:=NULL; NEW.scanned_at:=NULL;"
    commands = []
    for statement in re.split(r';\s*', body.strip()):
        statement = statement.strip()
        if not statement:
            continue
        conditional = re.fullmatch(r"SELECT CASE WHEN (.*) THEN RAISE\(ABORT,('(?:''|[^'])*')\) END", statement, re.S)
        reject = re.fullmatch(r"SELECT RAISE\(ABORT,('(?:''|[^'])*')\)", statement, re.S)
        if conditional:
            statement = f"IF {conditional[1]} THEN RAISE EXCEPTION {conditional[2]} USING ERRCODE='23514'; END IF"
        elif reject:
            statement = f"RAISE EXCEPTION {reject[1]} USING ERRCODE='23514'"
        if 'INSERT OR IGNORE' in statement:
            statement = statement.replace('INSERT OR IGNORE', 'INSERT') + ' ON CONFLICT DO NOTHING'
        commands.append(expression(statement) + ';')
    # SQLite's null-safe IS NOT also accepts a quoted RHS.
    condition = expression(condition.strip()[5:]) if condition.strip().startswith('WHEN ') else ''
    condition = re.sub(r'\bIS NOT\s+(?=\')', 'IS DISTINCT FROM ', condition)
    code = '\n '.join(commands)
    code = code.replace('SET revision=revision+1', 'SET revision=record_versions.revision+1') if 'INSERT INTO record_versions' in code else code
    if condition:
        code = f'IF {condition} THEN\n {code}\n END IF;'
    return (f'CREATE FUNCTION ecc_trigger_{name}() RETURNS trigger LANGUAGE plpgsql AS $trigger$\n'
            f'BEGIN\n {code}\n RETURN {"OLD" if event == "DELETE" else "NEW"};\nEND $trigger$;\n'
            f'CREATE TRIGGER {name} {timing} {event} ON {table} FOR EACH ROW EXECUTE FUNCTION ecc_trigger_{name}();\n')


def generate():
    connection = sqlite3.connect(':memory:')
    connection.create_function('business_offset', 0, lambda: '480 minutes')
    for path in sorted(path for path in (ROOT / 'migrations').glob('*.sql') if path.name <= '0014_business_clock.sql'):
        connection.executescript(path.read_text())
    objects = connection.execute("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type,name").fetchall()
    result = ['-- PostgreSQL baseline: 49 tables, all legacy constraints, audit and financial triggers.\n',
              (ROOT / 'scripts/postgres-functions.sql').read_text()]
    foreign_keys, extra_indexes = [], []
    for kind, name, table, sql in objects:
        if kind != 'table':
            continue
        sql = re.sub(r'--[^\n]*', '', sql)
        sql = re.sub(r"typeof\((\w+)\)='integer' AND ", '', sql)
        sql = re.sub(r'\bINTEGER PRIMARY KEY AUTOINCREMENT\b', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql)
        sql = re.sub(r'\bINTEGER\b', 'BIGINT', sql)
        sql = re.sub(r'\bDATE\b', 'TEXT', sql)
        sql = re.sub(r'\bBLOB\b', 'BYTEA', sql)
        sql = sql.replace('DEFAULT CURRENT_DATE', "DEFAULT (ecc_date('now'))")
        # Integer flags remain integers for unchanged JSON and field codecs.
        sql = re.sub(r'\((\w+ IS NOT NULL)\)', r'(CASE WHEN \1 THEN 1 ELSE 0 END)', sql)
        if 'COLLATE NOCASE' in sql:
            sql = sql.replace(',\n UNIQUE(template_id,title COLLATE NOCASE)', '')
            extra_indexes.append('CREATE UNIQUE INDEX checklist_items_title_unique ON checklist_template_items(template_id,lower(title));')
        def reference(match):
            column, ref, action = match.groups()
            foreign_keys.append(f'ALTER TABLE "{table}" ADD FOREIGN KEY ("{column}") REFERENCES {ref}{action or ""} DEFERRABLE INITIALLY IMMEDIATE;')
            return column + ' BIGINT'
        sql = re.sub(r'(\w+)\s+BIGINT\s+REFERENCES (\w+\(\w+\))( ON DELETE (?:SET NULL|CASCADE))?', reference, sql)
        # NOT NULL/UNIQUE/PRIMARY KEY may precede REFERENCES.
        def other_reference(match):
            column, flags, ref, action = match.groups()
            foreign_keys.append(f'ALTER TABLE "{table}" ADD FOREIGN KEY ("{column}") REFERENCES {ref}{action or ""} DEFERRABLE INITIALLY IMMEDIATE;')
            return column + ' BIGINT ' + flags
        sql = re.sub(r'(\w+)\s+BIGINT\s+((?:(?:NOT NULL|UNIQUE|PRIMARY KEY)\s+)+)REFERENCES (\w+\(\w+\))( ON DELETE (?:SET NULL|CASCADE))?', other_reference, sql)
        sql = expression(sql)
        sql = re.sub(r'jsonb_typeof\((\w+)\)', r'jsonb_typeof(\1::jsonb)', sql)
        result.append(sql + ';\n')
    result += foreign_keys + extra_indexes
    for kind, name, table, sql in objects:
        if kind == 'index':
            sql = re.sub(r'(\w+) COLLATE NOCASE', r'lower(\1)', sql)
            result.append(expression(sql) + ';')
        elif kind == 'view':
            result.append(expression(sql) + ';')
    for kind, name, table, sql in objects:
        if kind == 'trigger':
            result.append(trigger(sql))
    for kind, name, table, sql in objects:
        if kind == 'table':
            result.append(f'CREATE TRIGGER ecc_lock BEFORE INSERT OR UPDATE OR DELETE ON "{name}" FOR EACH STATEMENT EXECUTE FUNCTION ecc_write_lock();')
    connection.close()
    return '\n'.join(result) + '\n'


if __name__ == '__main__':
    (ROOT / 'migrations/postgresql/0001_postgresql.sql').write_text(generate())
